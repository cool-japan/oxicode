//! Committed golden-vector corpus for wire-format compatibility with bincode 2.0.1.
//!
//! These byte vectors were generated once, offline, by encoding representative
//! values with the real `bincode = "=2.0.1"` crate (see the `#[ignore]`d
//! regeneration test in `tests/regen_golden_vectors.rs`, which prints an
//! up-to-date version of this file to stdout). They are then hard-coded here
//! as `const` data so that the compatibility test suite (and any downstream
//! consumer) can assert byte-for-byte parity WITHOUT depending on the live
//! `bincode` crate at test-run time, and so the assertions are reproducible on
//! any host (including big-endian / 32-bit targets where `bincode` itself may
//! not even be available to run as an oracle).
//!
//! Every type covered here is confirmed wire-compatible between oxicode and
//! bincode 2.0.1 (see `tests/bincode_compat_test.rs` and this crate's own
//! tests for the live cross-checks that originally produced this corpus).
//! Types with KNOWN divergences (`SystemTime`, `SocketAddrV6`, `IpAddr` /
//! `SocketAddr` / `Bound` under fixed-int configs, `Path` / `PathBuf`,
//! `Ordering`) are intentionally NOT part of this corpus — see
//! `tests/hardening_m1_divergent_self_roundtrip_test.rs` for their
//! self-roundtrip stability vectors and the documented, `#[ignore]`d
//! cross-tests that specify the expected divergence.
//!
//! Four configuration combinations are covered, matching the (endianness x
//! int-encoding) matrix bincode itself exposes:
//! - `LE_VARINT`: `oxicode::config::standard()` == little-endian + varint
//! - `LE_FIXINT`: `oxicode::config::legacy()` == little-endian + fixed-int
//! - `BE_VARINT`: `oxicode::config::standard().with_big_endian()`
//! - `BE_FIXINT`: `oxicode::config::legacy().with_big_endian()`
//!
//! Each table is a slice of `(name, expected_bytes)` pairs; the `name` matches
//! the corresponding encode call in the golden-vector test module so failures
//! are easy to trace back to a concrete Rust value.

/// Look up a named golden vector in one of the tables below.
///
/// # Panics
///
/// Panics if `name` is not present in `table` — this is test-only helper
/// code, and an absent name indicates a corpus/test mismatch that should fail
/// loudly rather than silently returning an empty slice.
pub fn lookup<'a>(table: &[(&str, &'a [u8])], name: &str) -> &'a [u8] {
    table
        .iter()
        .find(|(n, _)| *n == name)
        .unwrap_or_else(|| panic!("golden vector '{name}' not found in table"))
        .1
}

